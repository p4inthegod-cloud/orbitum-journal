import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const styles = ['sections','refresh','polish','pixel','world','concept','quest','details','orientation','craft','trend-chart','decision','coins','watchtower','audit','live','ledger','atlas','position','okx'];
const head = ['pixel','world','concept','quest','details','orientation','craft','trend-chart','market-registry','decision','coins','watchtower'];
const tail = ['wave-chart','audit','atlas','live','ledger-model','ledger','okx'];
function bundle(names, extension, label) {
  let content = '/* Generated by scripts/build-journal-assets.mjs. Edit the source modules. */\n' + names.map(name => {
    const file = `${extension}/journal-${name}.${extension}`;
    return `\n/* ${file} */\n${fs.readFileSync(path.join(root,file),'utf8').replace(/\r\n/g,'\n')}\n${extension==='js'?';':''}`;
  }).join('\n');
  if(extension==='css')content=content.trimEnd()+'\n';
  const hash = createHash('sha256').update(content).digest('hex').slice(0,12);
  const file = `${extension}/journal-${label}-${hash}.${extension}`;
  fs.writeFileSync(path.join(root,file),content);
  return file;
}
const css=bundle(styles,'css','ui'),js=bundle(head,'js','ui'),runtime=bundle(tail,'js','runtime');
const file=path.join(root,'journal.html');let html=fs.readFileSync(file,'utf8');
const headMarkup=`<!-- JOURNAL ASSETS START -->\n<link rel="stylesheet" href="${css}" data-journal-styles>\n<script src="${js}"></script>\n<!-- JOURNAL ASSETS END -->`;
if(html.includes('<!-- JOURNAL ASSETS START -->'))html=html.replace(/<!-- JOURNAL ASSETS START -->[\s\S]*?<!-- JOURNAL ASSETS END -->/,headMarkup);
else html=html.replace(/<link rel="stylesheet" href="css\/journal-sections.css">[\s\S]*?<link rel="stylesheet" href="css\/journal-atlas.css">/,headMarkup);
const tailMarkup=`<!-- JOURNAL RUNTIME START -->\n<script src="${runtime}"></script>\n<!-- JOURNAL RUNTIME END -->`;
if(html.includes('<!-- JOURNAL RUNTIME START -->'))html=html.replace(/<!-- JOURNAL RUNTIME START -->[\s\S]*?<!-- JOURNAL RUNTIME END -->/,tailMarkup);
else html=html.replace(/<script src="js\/journal-wave-chart.js"><\/script>[\s\S]*?<script src="js\/journal-atlas.js"><\/script>/,tailMarkup);
html=html.replace(/<!-- JOURNAL PRELOAD START -->[\s\S]*?<!-- JOURNAL PRELOAD END -->\n?/,'');
const icons=['compass','gem','scroll','target','owl','chest','pickaxe','crystal-purple'].map(name=>`<link rel="preload" href="assets/pixel-pack/${name}.webp" as="image">`).join('\n');
const preload=`<!-- JOURNAL PRELOAD START -->\n<link rel="preload" href="${css}" as="style">\n<link rel="preload" href="${js}" as="script">\n<link rel="preload" href="assets/fonts/Tiny5-Regular.ttf" as="font" type="font/ttf" crossorigin>\n${icons}\n<!-- JOURNAL PRELOAD END -->\n`;
html=html.replace('<link rel="icon"',preload+'<link rel="icon"');fs.writeFileSync(file,html);
console.log(JSON.stringify({css,js,runtime}));
